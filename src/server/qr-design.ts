import { festivalTheme as getFestivalTheme } from "../lib/festival-themes";
import {
  qrCustomizationSchema,
  readableInk,
  scannableInk,
  type QRCustomization,
} from "../lib/qr-design";
import QRCode from "qrcode";
import sharp from "sharp";
import { qrColors, type QRColor, type QRTemplate } from "../lib/qr-design";

const escapeXml = (text: string) =>
  text.replace(
    /[&<>"']/g,
    (character) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&apos;",
      })[character]!,
  );
export async function restaurantQR({
  name,
  url,
  template,
  color,
  poster,
  customization,
  festival,
}: {
  name: string;
  url: string;
  template: QRTemplate;
  color: QRColor;
  poster: boolean;
  festival?: string;
  customization?: Partial<QRCustomization>;
}) {
  const design = qrCustomizationSchema.parse({
    accent: qrColors.find((entry) => entry.id === color)!.value,
    ...customization,
  });
  const seasonal = getFestivalTheme(festival);
  if (seasonal.greeting) {
    design.accent = seasonal.accent;
    design.background = seasonal.background;
  }
  const { accent, background, radius, size, font } = design;
  const border = customization?.border ?? (template === "frame" ? 30 : 0);
  const ink = readableInk(background);
  const qr = await QRCode.toBuffer(url, {
    width: 720,
    margin: 4,
    errorCorrectionLevel: "H",
    color: { dark: scannableInk(accent), light: "#ffffff" },
  });
  if (!poster) return qr;
  // Embed generated bytes only: no arbitrary image URLs or external SVG resources.
  const lines = Array.from(name)
    .reduce<string[]>((result, letter) => {
      if (!result.length || Array.from(result[result.length - 1]).length >= 28)
        result.push("");
      result[result.length - 1] += letter;
      return result;
    }, [])
    .slice(0, 4);
  const title = lines
    .map(
      (line, i) =>
        `<text x="500" y="${105 + i * 48}" font-size="40" font-weight="700">${escapeXml(line)}</text>`,
    )
    .join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="1000" height="1400" viewBox="0 0 1000 1400">
    ${seasonal.greeting ? `<desc>${escapeXml(seasonal.name)} restaurant menu design</desc>` : ""}
    <rect width="1000" height="1400" fill="${accent}"/>
    <rect x="${border}" y="${border}" width="${1000 - border * 2}" height="${1400 - border * 2}" rx="${radius}" fill="${background}"/>
    ${template === "bold" ? `<path d="M30 54 Q30 30 54 30 H946 Q970 30 970 54 V300 H30Z" fill="${accent}"/>` : ""}
    ${seasonal.greeting ? `<g fill="${accent}" opacity="0.5"><circle cx="85" cy="420" r="16"/><circle cx="915" cy="420" r="16"/><circle cx="85" cy="1050" r="16"/><circle cx="915" cy="1050" r="16"/></g>` : ""}
    <g font-family="${font}" text-anchor="middle" fill="${template === "bold" ? readableInk(accent) : ink}">${title}</g>
    <text x="500" y="350" font-family="${font}" text-anchor="middle" font-size="24" letter-spacing="4" fill="${ink}">${escapeXml(seasonal.greeting ? seasonal.greeting.toUpperCase() : "YOUR NEXT FAVOURITE AWAITS")}</text>
    <image x="${(1000 - size) / 2}" y="${380 + (720 - size) / 2}" width="${size}" height="${size}" xlink:href="data:image/png;base64,${qr.toString("base64")}"/>
    <g font-family="${font}" text-anchor="middle" fill="${ink}">
      <text x="500" y="1150" font-size="${Math.min(52, 1400 / Math.max(1, design.heading.length))}" font-weight="700">${escapeXml(design.heading)}</text>
      <text x="500" y="1210" font-size="${Math.min(26, 1400 / Math.max(1, design.subtitle.length))}">${escapeXml(design.subtitle)}</text>
      <text x="500" y="1260" font-size="24">No app. No signup. Pay at the counter.</text>
      <text x="500" y="1330" font-size="22">Powered by TableBabu</text>
    </g></svg>`;
  return sharp(Buffer.from(svg)).png().toBuffer();
}
